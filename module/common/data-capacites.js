/**
 * Les 68 capacités spéciales (livre de base p.207-218), classées par
 * caractéristique. Descriptions paraphrasées (pas de reproduction mot
 * pour mot du livret). Source unique utilisée à la fois par
 * tools/build-compendium-source.mjs (pour le compendium) et par
 * module/actor/sheet/intre-sheet.js (pour le sélecteur sur la fiche).
 *
 * Chaque capacité porte désormais un champ `eligibilite` (livre p.207) :
 *  - natif      : races qui possèdent la capacité de naissance (ne peut
 *                 pas être choisie une seconde fois).
 *  - evolution  : races qui peuvent l'acquérir sans coût de Souillure
 *                 (tableau de clés de race, ou "toutes" pour toutes les
 *                 races).
 *  - souillure  : { race: coût } — races qui peuvent l'acquérir au prix
 *                 d'une augmentation de Souillure ; { toutes: coût } si
 *                 valable pour toutes les races.
 *  - note       : précision complémentaire quand la règle est
 *                 conditionnelle (ex : liée à la caste) ou quand le
 *                 livret ne donne pas une liste complète (gap assumé,
 *                 signalé explicitement plutôt que deviné).
 *
 * Clés de race utilisées : apis, blatere, brindis, cerk, crinar,
 * crinelle, koksihne, lepide, lulle, mantide, myrmide, putere, skadan,
 * skarab, stick, syrphe, termide, vespale, arakchass, araktiss (mêmes
 * clés que module/common/data-races.js).
 *
 * Les capacités qui sont en réalité des armes naturelles (Griffes
 * acérées, Mandibules hypertrophiées, Ravisseuses, Pinces démesurées,
 * Défenses) restent listées ici (elles peuvent être choisies comme
 * capacité à la création) mais sont AUSSI modélisées comme Items "arme"
 * (voir tools/build-compendium-source.mjs) pour l'automatisation des
 * dégâts.
 */
function cap(name, categorie, souillureCout, fluideCout, description, bonus, eligibilite) {
  return {
    name,
    categorie,
    souillureCout,
    fluideCout,
    description,
    bonus: bonus ?? { actif: false, caracKey: "", compKey: "", valeur: 0 },
    eligibilite: eligibilite ?? { natif: [], evolution: [], souillure: {} },
  };
}

